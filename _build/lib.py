"""Shared page builder for the generated guide pages.

Each page module in _build/pages/ supplies metadata and a body template.
Citations are written as [[source_key]] and numbered automatically in order
of first use; the sources list at the foot of the page is generated from
_build/data/sources.json, so a source is defined once for every page.
"""
