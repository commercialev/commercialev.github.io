NAV = [('/electric-vans-uk/', 'Vans'), ('/electric-trucks-uk/', 'Trucks'), ('/electric-van-batteries/', 'Batteries'),
       ('/electric-van-fleets-uk/', 'Fleets'), ('/charging-an-electric-van/', 'Charging'),
       ('/diesel-vs-electric-vans/', 'Diesel vs electric'), ('/commercial-electric-vehicles-uk/', 'Grants &amp; rules')]


def load(name):
    with open(os.path.join(ROOT, 'data', name), encoding='utf-8') as f:
        return json.load(f)


SOURCES = load('sources.json')


def nav(current):
    out = []
    for href, label in NAV:
        cur = ' aria-current="page"' if href == current else ''
        out.append(f'      <a href="{href}"{cur}>{label}</a>')
    return '\n'.join(out)


def source_html(key):
    s = SOURCES[key]
    links = []
    for site, url, official in s['links']:
        rel = 'noopener' if official else 'nofollow noopener'
        links.append(f'<a href="{url}" rel="{rel}" target="_blank">{site}</a>')
    return s['label'] + ': ' + '; '.join(links)


def cite(body):
    """Replace [[key]] with numbered links in order of first use; return body and sources list HTML."""
    order = []

    def rep(m):
        k = m.group(1)
        if k not in SOURCES:
            raise KeyError(f'unknown source {k}')
        if k not in order:
            order.append(k)
        n = order.index(k) + 1
        return f'<a href="#s{n}">[{n}]</a>'

    body = re.sub(r'\[\[(\w+)\]\]', rep, body)
    lis = '\n'.join(f'      <li id="s{i + 1}">{source_html(k)}</li>' for i, k in enumerate(order))
    return body, lis


def refs(keys):
    """Citation markers for a list of source keys, e.g. '[[a]] [[b]]'."""
    return ' '.join(f'[[{k}]]' for k in keys)


